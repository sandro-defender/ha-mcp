"""Startup contract: S6-Overlay chain, AppArmor coverage, entrypoint, health.

These tests exist because a live Home Assistant OS host is not available in
this environment.  They cannot replace an HA OS boot, but they do catch the
regressions that produced the 0.3.x startup failures:

* ``/init`` and the S6 ``libexec`` scripts are ``#!/bin/sh`` scripts.  The
  kernel starts ``/bin/sh <script>``, so the interpreter must be able to
  *open* the file.  An AppArmor rule with only ``ix`` (execute) reproduces
  ``/bin/sh: can't open '/init': Permission denied``.
* ``s6-overlay-suexec: fatal: child failed with exit code 2`` is the suexec
  wrapper reporting that its ``preinit`` child died with the shell's exit
  code, i.e. the same read denial one stage later.

Docker/AppArmor are not available here, so the profile is verified statically:
each path the S6 chain executes must match a rule that grants read + execute
(or read + mmap for shared objects).
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest
import yaml

ADDON_DIR = Path(__file__).resolve().parents[1]
APPARMOR = (ADDON_DIR / "apparmor.txt").read_text(encoding="utf-8")
DOCKERFILE = (ADDON_DIR / "Dockerfile").read_text(encoding="utf-8")
RUN_SH = (ADDON_DIR / "run.sh").read_text(encoding="utf-8")
CONFIG = yaml.safe_load((ADDON_DIR / "config.yaml").read_text(encoding="utf-8"))

# The add-on does not build S6 itself: ghcr.io/home-assistant/base:3.24 ships
# S6-Overlay 3.2.3.2, whose scripts are these paths (s6-overlay v3.2.3.2
# layout, verified against the upstream release source).
S6_VERSION = "3.2.3.2"
S6_ROOT = f"/package/admin/s6-overlay-{S6_VERSION}"
S6_SCRIPTS = [
    "/init",
    f"{S6_ROOT}/libexec/preinit",
    f"{S6_ROOT}/libexec/stage0",
    f"{S6_ROOT}/libexec/fix-attrs",
    f"{S6_ROOT}/etc/s6-linux-init/skel/rc.init",
    f"{S6_ROOT}/etc/s6-linux-init/skel/rc.shutdown",
    "/run/s6/basedir/bin/init",  # generated by s6-linux-init-maker at boot
    "/run.sh",  # CMD, executed by the stage-2 rc.init
    "/etc/cont-init.d/00-example.sh",  # legacy stage-2 hook location
    "/etc/services.d/app/run",  # legacy service location
]
S6_BINARIES = [
    "/command/s6-svscan",
    "/command/s6-rc-compile",
    "/command/s6-linux-init-maker",
    "/command/s6-overlay-suexec",
    "/bin/sh",
    "/bin/busybox",  # Alpine resolves /bin/sh to the busybox applet
]
PYTHON_BINARIES = [
    "/opt/venv/bin/python",
    "/usr/bin/python3",
]
PYTHON_LIBRARIES = [
    "/opt/venv/lib/python3.13/site-packages/pydantic_core/_pydantic_core.cpython-313-x86_64-linux-musl.so",
    "/usr/lib/libc.musl-x86_64.so.1",
    "/lib/ld-musl-x86_64.so.1",
]


def _expand(pattern: str) -> str:
    """Translate an AppArmor path glob into a regular expression.

    Supports ``**`` (any depth), ``*`` (one path component) and ``{a,b}``
    alternation, which is the subset used by apparmor.txt.
    """

    out: list[str] = []
    index = 0
    while index < len(pattern):
        char = pattern[index]
        if char == "{":
            end = pattern.index("}", index)
            alternatives = pattern[index + 1 : end].split(",")
            out.append("(?:" + "|".join(_expand(alt) for alt in alternatives) + ")")
            index = end + 1
            continue
        if pattern.startswith("**", index):
            out.append(".*")
            index += 2
            continue
        if char == "*":
            out.append("[^/]*")
            index += 1
            continue
        out.append(re.escape(char))
        index += 1
    return "".join(out)


def _rules() -> list[tuple[str, str]]:
    rules: list[tuple[str, str]] = []
    for raw in APPARMOR.splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or line.startswith("/include"):
            continue
        match = re.fullmatch(r"(/\S*)\s+([a-zA-Z]+),", line)
        if match:
            rules.append((match.group(1), match.group(2)))
    return rules


def _permissions_for(path: str) -> set[str]:
    granted: set[str] = set()
    for pattern, perms in _rules():
        if re.fullmatch(_expand(pattern), path):
            granted.update(perms)
    # AppArmor's `x` modifier forms (ix, ux, px, cx, Px, Ux) all include
    # execute; `rix` contributes both r and x.
    return granted


@pytest.mark.parametrize("path", S6_SCRIPTS)
def test_s6_scripts_are_readable_and_executable(path: str) -> None:
    """Every S6 stage is a shell script: the interpreter must read it."""

    permissions = _permissions_for(path)
    assert "r" in permissions, f"{path} must be readable ({permissions})"
    assert "x" in permissions, f"{path} must be executable ({permissions})"


@pytest.mark.parametrize("path", S6_BINARIES)
def test_s6_binaries_are_executable(path: str) -> None:
    permissions = _permissions_for(path)
    assert "x" in permissions, f"{path} must be executable ({permissions})"


@pytest.mark.parametrize("path", PYTHON_BINARIES)
def test_python_runtime_is_executable_and_mappable(path: str) -> None:
    permissions = _permissions_for(path)
    assert "x" in permissions, f"{path} must be executable ({permissions})"
    assert "m" in permissions, f"{path} needs mmap (PROT_EXEC) access ({permissions})"


@pytest.mark.parametrize("path", PYTHON_LIBRARIES)
def test_shared_libraries_are_mappable(path: str) -> None:
    permissions = _permissions_for(path)
    assert "m" in permissions, f"{path} needs mmap (PROT_EXEC) access ({permissions})"
    assert "r" in permissions, f"{path} needs read access ({permissions})"


def test_profile_is_read_only_outside_state_directories() -> None:
    """Least privilege: no writes to system paths, only /data, /tmp, /run, /dev."""

    writable_prefixes = ("/data", "/tmp", "/run", "/dev")
    for pattern, perms in _rules():
        if "w" not in perms:
            continue
        assert pattern.startswith(writable_prefixes), f"unexpected write rule {pattern}"


def test_profile_does_not_grant_dangerous_privileges() -> None:
    lowered = APPARMOR.lower()
    for forbidden in (
        "capability sys_admin",
        "capability sys_ptrace",
        "capability sys_module",
        "capability net_admin",
        "network raw",
        "network packet",
        "mount,",
        "chmod 777",
        "chmod -r 777",
    ):
        assert forbidden not in lowered, forbidden

    # No catch-all file rule: everything the add-on touches is enumerated.
    for pattern, perms in _rules():
        assert pattern not in {"/**", "/**/*", "/*"}, pattern
        assert not (pattern.startswith("/**") and "w" in perms), pattern

    assert "profile ha_agent_gateway" in APPARMOR
    assert APPARMOR.count("\nprofile ") == 1


def test_profile_still_drops_privileges_before_the_application() -> None:
    """The profile keeps the minimum capabilities for the root entrypoint only."""

    assert "capability setuid" in APPARMOR
    assert "capability setgid" in APPARMOR
    assert "capability chown" in APPARMOR
    assert "su-exec" in RUN_SH
    assert 'if [ "$(id -u)" = "0" ]' in RUN_SH


def test_addon_does_not_override_the_s6_entrypoint() -> None:
    assert CONFIG["init"] is False  # the base image owns ENTRYPOINT /init
    assert "ENTRYPOINT" not in DOCKERFILE
    assert 'CMD ["/run.sh"]' in DOCKERFILE
    assert "chmod 0755 /run.sh" in DOCKERFILE
    assert "ghcr.io/home-assistant/base:3.24" in DOCKERFILE


def test_dockerfile_verifies_the_s6_chain_at_build_time() -> None:
    """The image build fails loudly if a future base image breaks the chain."""

    assert "test -x /init && test -r /init" in DOCKERFILE
    assert "libexec/preinit" in DOCKERFILE
    assert "/libexec/stage0" in DOCKERFILE or "stage0=" in DOCKERFILE
    assert "gateway imports ok" in DOCKERFILE


def test_run_script_keeps_production_defaults() -> None:
    assert 'DATA_DIR="${HAG_DATA_DIR:-/data}"' in RUN_SH
    assert 'PYTHON_BIN="${HAG_PYTHON:-/opt/venv/bin/python}"' in RUN_SH
    assert 'PYTHON_PATH="${HAG_PYTHONPATH:-/app/src}"' in RUN_SH
    assert 'APP_USER="${HAG_APP_USER:-app:app}"' in RUN_SH
    assert 'exec su-exec "$APP_USER" "$PYTHON_BIN" -m gateway "$@"' in RUN_SH
    assert 'exec "$PYTHON_BIN" -m gateway "$@"' in RUN_SH
    assert RUN_SH.startswith("#!/usr/bin/env bash\n")
    assert "\r" not in RUN_SH
    assert "set -euo pipefail" in RUN_SH


def test_health_and_readiness_contract_is_wired_everywhere() -> None:
    apps = (ADDON_DIR / "src" / "gateway" / "api" / "apps.py").read_text(encoding="utf-8")
    assert '@app.get("/healthz"' in apps
    assert '@app.get("/readyz"' in apps
    assert config_watchdog() == "http://[HOST]:[PORT:8099]/healthz"
    assert "HEALTHCHECK" in DOCKERFILE and "http://127.0.0.1:8099/healthz" in DOCKERFILE


def config_watchdog() -> str:
    config = yaml.safe_load((ADDON_DIR / "config.yaml").read_text(encoding="utf-8"))
    return str(config["watchdog"])
